import fs from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';

export const CLINICAL_TABLES = [
  'encounters',
  'encounter_addenda',
  'conditions',
  'allergies',
  'medications',
  'observations',
  'documents',
  'care_plans',
  'care_plan_items',
  'symptom_reports',
] as const;

export function generateAuditTriggers(): string {
  const baseDir = import.meta.dirname || path.dirname(new URL(import.meta.url).pathname);
  const schemaPath = path.resolve(baseDir, '../migrations/0001_schema.sql');
  const schemaSql = fs.readFileSync(schemaPath, 'utf8');

  const db = new DatabaseSync(':memory:');
  db.exec(schemaSql);

  const parts: string[] = [
    '-- ============================================================================',
    '-- Migration: 0003_audit_triggers.sql',
    '-- Description: Automated Audit Triggers for Clinical Tables',
    '-- Generated by scripts/gen-audit-triggers.ts',
    '-- Enforces _request_ctx presence and records detailed JSON diffs in audit_log',
    '-- ============================================================================',
    '',
  ];

  for (const table of CLINICAL_TABLES) {
    const rawCols = db.prepare(`PRAGMA table_info(${table})`).all() as Array<{ name: string }>;
    const cols = rawCols.map((c) => c.name);

    const oldJsonArgs = cols.map((c) => `'${c}', OLD.${c}`).join(', ');
    const newJsonArgs = cols.map((c) => `'${c}', NEW.${c}`).join(', ');

    // AFTER INSERT Trigger
    parts.push(`-- Audit Trigger for INSERT on ${table}`);
    parts.push(`CREATE TRIGGER IF NOT EXISTS trg_audit_insert_${table}`);
    parts.push(`AFTER INSERT ON ${table}`);
    parts.push('FOR EACH ROW');
    parts.push('BEGIN');
    parts.push("  SELECT RAISE(ABORT, 'Direct mutation prohibited without active _request_ctx')");
    parts.push('  WHERE (SELECT COUNT(*) FROM _request_ctx WHERE id = 1) = 0;');
    parts.push('');
    parts.push('  INSERT INTO audit_log (');
    parts.push('    at, actor_id, action, table_name, record_id, patient_id, old_row, new_row');
    parts.push('  )');
    parts.push('  VALUES (');
    parts.push("    datetime('now'),");
    parts.push('    (SELECT actor_id FROM _request_ctx WHERE id = 1),');
    parts.push("    'INSERT',");
    parts.push(`    '${table}',`);
    parts.push('    NEW.id,');
    parts.push('    NEW.patient_id,');
    parts.push('    NULL,');
    parts.push(`    json_object(${newJsonArgs})`);
    parts.push('  );');
    parts.push('END;');
    parts.push('');

    // AFTER UPDATE Trigger
    parts.push(`-- Audit Trigger for UPDATE on ${table}`);
    parts.push(`CREATE TRIGGER IF NOT EXISTS trg_audit_update_${table}`);
    parts.push(`AFTER UPDATE ON ${table}`);
    parts.push('FOR EACH ROW');
    parts.push('BEGIN');
    parts.push("  SELECT RAISE(ABORT, 'Direct mutation prohibited without active _request_ctx')");
    parts.push('  WHERE (SELECT COUNT(*) FROM _request_ctx WHERE id = 1) = 0;');
    parts.push('');
    parts.push('  INSERT INTO audit_log (');
    parts.push('    at, actor_id, action, table_name, record_id, patient_id, old_row, new_row');
    parts.push('  )');
    parts.push('  VALUES (');
    parts.push("    datetime('now'),");
    parts.push('    (SELECT actor_id FROM _request_ctx WHERE id = 1),');
    parts.push("    'UPDATE',");
    parts.push(`    '${table}',`);
    parts.push('    NEW.id,');
    parts.push('    NEW.patient_id,');
    parts.push(`    json_object(${oldJsonArgs}),`);
    parts.push(`    json_object(${newJsonArgs})`);
    parts.push('  );');
    parts.push('END;');
    parts.push('');
  }

  return parts.join('\n');
}

export function writeAuditTriggersFile(): void {
  const baseDir = import.meta.dirname || path.dirname(new URL(import.meta.url).pathname);
  const outputPath = path.resolve(baseDir, '../migrations/0003_audit_triggers.sql');
  const sql = generateAuditTriggers();
  fs.writeFileSync(outputPath, sql, 'utf8');
  console.log(`Generated audit triggers in ${outputPath}`);
}

// Run generator if invoked directly
writeAuditTriggersFile();
